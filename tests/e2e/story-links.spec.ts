import { _electron as electron, test, expect } from '@playwright/test'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from 'fs'
import { tmpdir } from 'os'
import { join, resolve } from 'path'
import { execFileSync } from 'child_process'

test('linked content, origins, batch operations and geometric workspaces', async () => {
  const root = mkdtempSync(join(tmpdir(), 'framebook-links-'))
  mkdirSync(join(root, '.app-data'))
  writeFileSync(join(root, '.app-data/settings.json'), JSON.stringify({ introMode: 'off', simplifyAnimations: true }))
  const source = join(root, 'portrait.mp4')
  execFileSync(join(process.cwd(), 'node_modules/ffmpeg-static/ffmpeg'), ['-y', '-f', 'lavfi', '-i', 'testsrc2=s=180x320:r=24:d=2', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', source], { stdio: 'ignore' })
  const mock = join(root, 'libtv')
  writeFileSync(mock, `#!${process.execPath}\nconst fs=require('fs');const a=process.argv.slice(2);const log=${JSON.stringify(mock + '.log')};fs.appendFileSync(log,JSON.stringify(a)+'\\n');if(a[0]==='node'&&a[1]==='upload1'&&!fs.existsSync(log+'.verified')){fs.writeFileSync(log+'.verified','1');console.error('temporary verification failure');process.exit(1)}let r={};if(a[0]==='upload')r={nodeKey:'upload1'};if(a[0]==='account')r={activeAccount:{accountName:'Test account'}};if(a[0]==='workspace')r={folders:[]};if(a[0]==='project'&&a[1]==='list')r={projects:[{uuid:'canvas1',name:'Test canvas'}]};else if(a[0]==='project')r={projectUuid:'canvas1',nodes:[{id:'node1',name:'Image generator',type:'image',position:{x:0,y:0}},{id:'node2',name:'Video generator',type:'video',position:{x:480,y:0}}],edges:[]};if(a[0]==='node')r={nodeKey:a[1],data:{type:'image',params:{prompt:'Original prompt'},url:[]}};if(a[0]==='model')r=a[1]==='search'?{matches:[{modelName:'Test model',description:'Isolated test'}]}:{schema:{properties:{ratio:{enum:['9:16','16:9'],default:'9:16'},count:[1,2]}}};console.log(JSON.stringify(r));`, { mode: 0o700 })
  const app = await electron.launch({ ...(process.env.FRAMEBOOK_APP ? { executablePath: process.env.FRAMEBOOK_APP, args: [] } : { args: ['out/main/index.js'] }), env: { ...process.env, SBR_SMOKE_DIR: root, SBR_LIBTV_BIN: mock } })
  const output = resolve('../outputs/framebook-2.9')
  mkdirSync(output, { recursive: true })
  try {
    const page = await app.firstWindow()
    await page.addStyleTag({ content: '*,*::before,*::after{animation-duration:0s!important;transition-duration:0s!important}' })
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setContentSize(1440, 900))
    await page.locator('.language-select').selectOption('en')
    await page.screenshot({ path: join(output, 'welcome.png') })
    const fixture = await page.evaluate(async path => {
      const folder = await window.sbr.createProject('Geometric study')
      let state = window.__sbr.store.getState()
      state.newProject(folder, 'Geometric study')
      const media = state.addMedia(await window.sbr.importMedia(folder, path))
      const a = state.addFrame(media.id, .3, 'Portrait A'), b = state.addFrame(media.id, .8, 'Portrait B')
      state.setFrameContent(a.id, 'First content')
      state.setFrameContent(b.id, 'Second content')
      state.addShots([a.id, b.id], true)
      state = window.__sbr.store.getState()
      const first = state.doc.storyboard.shots[0].id
      state.addShots([a.id], true)
      state = window.__sbr.store.getState()
      const second = state.doc.storyboard.shots[1].id
      state.setFrameContent(a.id, 'Independent second shot', second)
      state.setImageOrigin(a.id, 'ai')
      state.updateStoryCell(first, 'shotNo', 7)
      state.selectFrame(a.id)
      state.mutate('test binding', (doc: import('../../src/shared/types').Project) => { doc.settings.libtv = { projectId: 'canvas1', name: 'Test canvas' } })
      await window.sbr.saveProject(folder, JSON.stringify(window.__sbr.store.getState().doc))
      return { folder, first, second, a: a.id, b: b.id }
    }, source)
    await expect(page.getByRole('textbox', { name: 'Linked shot number', exact: true })).toHaveValue('7')
    await expect(page.getByRole('textbox', { name: 'Linked shot number', exact: true })).toHaveAttribute('readonly', '')
    await expect(page.getByRole('textbox', { name: 'Content', exact: true })).toHaveValue('First content\n\nSecond content')
    await page.getByRole('combobox', { name: 'Linked shot', exact: true }).selectOption(fixture.second)
    await expect(page.getByRole('textbox', { name: 'Content', exact: true })).toHaveValue('Independent second shot')
    await page.getByRole('textbox', { name: 'Content', exact: true }).fill('Edited from capture')
    expect(await page.evaluate(id => window.__sbr.store.getState().doc.storyboard.shots.find((shot: { id: string }) => shot.id === id).cells.description, fixture.first)).toBe('First content\n\nSecond content')
    expect(await page.evaluate(id => window.__sbr.store.getState().doc.storyboard.shots.find((shot: { id: string }) => shot.id === id).cells.description, fixture.second)).toBe('Edited from capture')
    await page.screenshot({ path: join(output, 'capture.png') })
    const menu = await app.evaluate(({ Menu }) => Menu.getApplicationMenu()?.items.find(item => item.label === 'Panels')?.submenu?.items.map(item => item.label))
    expect(menu).toContain('Media bin')
    await page.evaluate(() => window.__sbr.store.getState().setWorkspace('storyboard'))
    await expect(page.locator('.story-table')).toBeVisible()
    await expect(page.locator('.origin-badge').first()).toHaveText('AI generated')
    await page.getByRole('checkbox', { name: 'Select all shots', exact: true }).check()
    await expect(page.getByRole('toolbar', { name: 'Selected shots' })).toContainText('2')
    await page.getByRole('toolbar', { name: 'Selected shots' }).getByRole('button', { name: 'Duplicate', exact: true }).click()
    expect(await page.evaluate(() => window.__sbr.store.getState().doc.storyboard.shots.length)).toBe(4)
    await page.evaluate(() => window.__sbr.store.getState().undo())
    expect(await page.evaluate(() => window.__sbr.store.getState().doc.storyboard.shots.length)).toBe(2)
    await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await page.locator('.storyboard-workspace').focus()
    await page.keyboard.press('Meta+a')
    await expect(page.getByRole('toolbar', { name: 'Selected shots' })).toContainText('2')
    await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await page.screenshot({ path: join(output, 'storyboard.png') })
    await page.getByRole('button', { name: 'Export…', exact: true }).click()
    await page.getByRole('button', { name: 'PDF storyboard', exact: true }).click()
    await expect(page.locator('.pdf-page-canvas canvas')).toBeVisible()
    await page.screenshot({ path: join(output, 'export-preview.png') })
    await page.keyboard.press('Escape')
    for (const workspace of ['gallery', 'planning', 'callsheet'] as const) {
      await page.evaluate(value => window.__sbr.store.getState().setWorkspace(value), workspace)
      await page.screenshot({ path: join(output, `${workspace}.png`) })
    }
    await page.evaluate(() => window.__sbr.store.getState().setWorkspace('libtv'))
    await expect(page.locator('.libtv-node').first()).toBeVisible()
    await page.locator('.libtv-node').first().click()
    await expect(page.locator('.libtv-floating-composer')).toBeVisible()
    await page.locator('.libtv-floating-composer textarea').fill('Keep this draft')
    await page.locator('.libtv-node-list button').nth(1).click()
    await page.locator('.libtv-node-list button').first().click()
    await expect(page.locator('.libtv-floating-composer textarea')).toHaveValue('Keep this draft')
    await page.getByRole('button', { name: 'Close editor', exact: true }).click()
    const before = await page.locator('.libtv-world').getAttribute('style')
    await page.locator('.libtv-canvas').dispatchEvent('wheel', { deltaX: 30, deltaY: 20, ctrlKey: false })
    await expect(page.locator('.libtv-world')).not.toHaveAttribute('style', before!)
    await page.locator('.libtv-canvas').click({ button: 'right', position: { x: 20, y: 20 } })
    await expect(page.getByRole('menu')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('menu')).toHaveCount(0)
    await page.evaluate(id => window.dispatchEvent(new CustomEvent('libtv-upload', { detail: { frameIds: [id], direct: true, position: { x: 120, y: 260 } } })), fixture.a)
    await expect(page.locator('.transfer-node').getByRole('button', { name: 'Retry failed files' })).toBeVisible()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.locator('.transfer-node').getByRole('button', { name: 'Retry failed files' }).click()
    await expect(page.locator('.transfer-node')).toHaveCount(0)
    const calls = readFileSync(mock + '.log', 'utf8').trim().split('\n').map(line => JSON.parse(line) as string[])
    expect(calls.filter(args => args[0] === 'upload')).toHaveLength(1)
    const upload = calls.find(args => args[0] === 'upload')!
    expect(upload[upload.indexOf('--x') + 1]).toBe('120')
    expect(upload[upload.indexOf('--y') + 1]).toBe('260')
    await page.screenshot({ path: join(output, 'libtv.png') })
    for (const size of [[1100, 700], [1920, 1080]]) {
      await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0]!.setContentSize(size[0]!, size[1]!), size)
      const bounds = await page.locator('.app').boundingBox()
      expect(Math.round(bounds!.width)).toBe(size[0])
      expect(Math.round(bounds!.height)).toBe(await page.evaluate(() => innerHeight))
    }
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setContentSize(1280, 800))
    await page.locator('.language-select').selectOption('zh-CN')
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.screenshot({ path: join(output, 'settings.png') })
    await page.getByRole('button', { name: '项目设置', exact: true }).click()
    await page.screenshot({ path: join(output, 'project-settings.png') })
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '项目库', exact: true }).click()
    await page.screenshot({ path: join(output, 'project-library.png') })
    await page.keyboard.press('Escape')
    const reopened = await page.evaluate(async folder => { const state = window.__sbr.store.getState(); await window.sbr.saveProject(folder, JSON.stringify(state.doc)); return await window.sbr.loadProject(folder) }, fixture.folder)
    expect(JSON.stringify(reopened)).toContain('Edited from capture')
    expect(JSON.stringify(reopened)).toContain('sourceFrameId')
  } finally { await app.close() }
})
